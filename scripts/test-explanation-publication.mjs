import {mkdtemp,readFile,writeFile,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import assert from 'node:assert/strict';
import {publishExplanations} from './publish-explanations.mjs';
import {referenceTitle} from './explanation-references.mjs';
import {validateExplanationMarkdown} from './explanation-markdown.mjs';
const directory=await mkdtemp(path.resolve('backend/target/publication-test-'));
const sha=text=>createHash('sha256').update(text).digest('hex');
const artifact=(text,file='generated/example-1.md')=>({entry:{sourceKey:sha('question'),title:'题目',baselineAnswerSha256:sha('old'),answerSha256:sha(text),file,topic:'test',references:[]},content:text});
const readManifest=()=>readFile(path.join(directory,'manifest.json'),'utf8');
const first=await publishExplanations(directory,'explanations-v1',[artifact('first')]);
const firstPath=path.join(directory,first.entries[0].file),firstStat=await stat(firstPath);
await publishExplanations(directory,'explanations-v1',[artifact('first')]);
assert.equal((await stat(firstPath)).mtimeMs,firstStat.mtimeMs,'Rerun rewrote immutable content');
const previous=await readManifest();
await assert.rejects(publishExplanations(directory,'explanations-v2',[artifact('second','../escape.md')]));
assert.equal(await readManifest(),previous,'Invalid generation replaced the live manifest');
const second=await publishExplanations(directory,'explanations-v2',[artifact('second')]);
assert.notEqual(second.entries[0].file,first.entries[0].file);
await assert.rejects(stat(firstPath),{code:'ENOENT'},'Stale snapshot survived successful republication');
await writeFile(path.join(directory,second.entries[0].file),'tampered');
const current=await readManifest();
await assert.rejects(publishExplanations(directory,'explanations-v2',[artifact('second')]));
assert.equal(await readManifest(),current,'Corrupt snapshot changed the manifest');
assert.match(referenceTitle('https://www.rfc-editor.org/rfc/rfc9293.html'),/TCP/);
assert.doesNotMatch(referenceTitle('https://ocw.mit.edu/courses/6-006/'),/HTTP/);
assert.throws(()=>validateExplanationMarkdown('## 参考回答\n## 参考分析\n## 案例\n## 总结点'));
console.log('PASS: immutable content, atomic manifest publication, failed-build preservation, idempotency, stale snapshot pruning and accurate source labels.');
