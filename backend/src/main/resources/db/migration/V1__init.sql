CREATE TABLE accounts (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL,
 last_question BIGINT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(200) NOT NULL UNIQUE, sort_order INT NOT NULL DEFAULT 0);
CREATE TABLE tags (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE questions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(1000) NOT NULL,
 category_id BIGINT NOT NULL, difficulty VARCHAR(30) NOT NULL,
 answer MEDIUMTEXT NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 deleted BOOLEAN NOT NULL DEFAULT FALSE, version INT NOT NULL DEFAULT 0,
 source_key VARCHAR(64) UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id)
);
CREATE INDEX idx_questions_category ON questions(category_id, deleted, sort_order);
CREATE TABLE question_tags (question_id BIGINT NOT NULL, tag_id BIGINT NOT NULL, PRIMARY KEY(question_id,tag_id),
 FOREIGN KEY(question_id) REFERENCES questions(id), FOREIGN KEY(tag_id) REFERENCES tags(id));
CREATE TABLE progress (user_id BIGINT NOT NULL, question_id BIGINT NOT NULL,
 mastery VARCHAR(20) NOT NULL DEFAULT 'NEW', favorite BOOLEAN NOT NULL DEFAULT FALSE,
 note MEDIUMTEXT NOT NULL, review_count INT NOT NULL DEFAULT 0, reviewed_at TIMESTAMP NULL,
 PRIMARY KEY(user_id,question_id), FOREIGN KEY(user_id) REFERENCES accounts(id), FOREIGN KEY(question_id) REFERENCES questions(id));
CREATE TABLE documents (id BIGINT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(200) NOT NULL UNIQUE, content MEDIUMTEXT NOT NULL);
